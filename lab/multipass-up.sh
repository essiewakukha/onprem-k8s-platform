#!/usr/bin/env bash
# Spin up a local Ubuntu 22.04 lab (1 control plane + N workers) with
# Multipass, then write the Ansible inventory and lab overrides.
#
#   ./lab/multipass-up.sh            # 3 workers
#   WORKERS=2 ./lab/multipass-up.sh  # lighter: needs ~9 GB RAM
set -Eeuo pipefail

WORKERS="${WORKERS:-3}"
CPUS="${CPUS:-2}"
MEMORY="${MEMORY:-3G}"
DISK="${DISK:-25G}"
PUBKEY="${SSH_PUBKEY:-${HOME}/.ssh/id_ed25519.pub}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

command -v multipass >/dev/null || { echo "Install Multipass first: https://multipass.run" >&2; exit 1; }
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }
[[ -f "${PUBKEY}" ]] || { echo "No SSH public key at ${PUBKEY} (set SSH_PUBKEY)" >&2; exit 1; }

cloud_init="$(mktemp)"
trap 'rm -f "${cloud_init}"' EXIT
cat > "${cloud_init}" <<EOF
#cloud-config
ssh_authorized_keys:
  - $(cat "${PUBKEY}")
EOF

nodes=(cp1)
for i in $(seq 1 "${WORKERS}"); do nodes+=("wk${i}"); done

for n in "${nodes[@]}"; do
  if multipass info "k8s-${n}" >/dev/null 2>&1; then
    echo "k8s-${n} already exists, skipping"
  else
    echo "Launching k8s-${n}..."
    multipass launch 22.04 --name "k8s-${n}" --cpus "${CPUS}" --memory "${MEMORY}" \
      --disk "${DISK}" --cloud-init "${cloud_init}"
  fi
done

ip_of() { multipass info "k8s-$1" --format json | jq -r ".info[\"k8s-$1\"].ipv4[0]"; }

inventory="${REPO_ROOT}/ansible/inventory/hosts.ini"
{
  echo "# Generated by lab/multipass-up.sh"
  echo "[control_plane]"
  echo "cp1 ansible_host=$(ip_of cp1)"
  echo
  echo "[workers]"
  for i in $(seq 1 "${WORKERS}"); do echo "wk${i} ansible_host=$(ip_of "wk${i}")"; done
  echo
  echo "[k8s_cluster:children]"
  echo "control_plane"
  echo "workers"
  echo
  echo "[k8s_cluster:vars]"
  echo "ansible_user=ubuntu"
  echo "ansible_ssh_common_args='-o StrictHostKeyChecking=accept-new'"
} > "${inventory}"

subnet="$(ip_of cp1 | cut -d. -f1-3)"
replicas=$(( WORKERS < 2 ? 1 : 2 ))
cat > "${REPO_ROOT}/lab/lab-vars.yml" <<EOF
# Generated by lab/multipass-up.sh. Use with: ansible-playbook site.yml -e @../lab/lab-vars.yml
metallb_ip_range: "${subnet}.240-${subnet}.250"
kube_vip_interface: "ens3"
registry_host: "lab.local"
longhorn_replica_count: ${replicas}
EOF

echo
echo "Inventory: ${inventory}"
echo "Lab vars:  lab/lab-vars.yml (MetalLB range ${subnet}.240-250)"
echo
echo "Next: make deps && cd ansible && ansible-playbook site.yml -e @../lab/lab-vars.yml"